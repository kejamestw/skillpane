const {test,expect}=require('./fixtures.cjs');

test('scan history baseline, changes, filters, safe text, navigation and persistence',async({page,fixtureURL})=>{
  await page.locator('#searchInput').fill('fixture-000');
  await page.locator('#skillList .skill-row').first().click();
  await page.locator('#noteInput').fill('Synthetic history navigation draft');
  await page.locator('#changesButton').click();
  await expect(page.locator('#changesDialog')).toBeVisible();
  await expect(page.locator('.change-empty strong')).toHaveText('基準已建立，尚無變更紀錄');
  const response=await page.request.post(fixtureURL+'/api/fixture/changes',{data:{},headers:{Origin:fixtureURL,'X-Skillpane-Client':'1'}});
  expect(response.ok()).toBeTruthy();
  await page.locator('#scanChanges').click();
  await expect(page.locator('.change-row')).toHaveCount(14);
  await expect(page.locator('#changesError')).toBeHidden();
  await page.locator('#changeKind').selectOption('added');
  await expect(page.locator('.change-row')).toHaveCount(1);
  await expect(page.locator('.change-row strong')).toContainText('<img');
  expect(await page.evaluate(()=>Boolean(window.__historyXss))).toBe(false);
  await expect(page.locator('#changesList img')).toHaveCount(0);
  await page.locator('#changeKind').selectOption('missing');
  await expect(page.locator('.change-row')).toHaveCount(1);
  await expect(page.locator('.change-row button')).toHaveCount(0);
  await page.locator('#changeKind').selectOption('changed');
  await expect(page.locator('.change-row')).toHaveCount(12);
  await page.locator('#changeSearch').fill('fixture-000');
  // Two sources share this name; select the personal record explicitly.
  const row=page.locator('.change-row').filter({hasText:'個人技能'});
  await row.locator('button').click();
  await expect(page.locator('#changesDialog')).not.toBeVisible();
  await expect(page.locator('#noteInput')).toHaveValue('Synthetic history navigation draft');
  await page.locator('#saveNoteButton').click();
  await page.locator('#changesButton').click();
  await page.locator('#changeKind').selectOption('');
  await page.locator('#changeSearch').fill('');
  await page.locator('#changesList').hover();await page.mouse.wheel(0,1200);
  await expect.poll(()=>page.locator('#changesList').evaluate(node=>node.scrollTop)).toBeGreaterThan(0);
  await page.locator('#scanChanges').click();
  await expect(page.locator('.change-row')).toHaveCount(14);
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('#skillList .skill-row').first()).toBeVisible();
  await page.locator('#changesButton').click();
  await expect(page.locator('.change-row')).toHaveCount(14);
  await page.keyboard.press('Escape');
  await page.locator('#quickSettingsButton').click();
  await page.locator('#textSizeSelect').selectOption('extra-large');
  await page.locator('#closeSettings').click();
  await page.locator('#changesButton').click();
  expect(await page.locator('#changesDialog').evaluate(node=>node.scrollWidth<=node.clientWidth+1)).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
